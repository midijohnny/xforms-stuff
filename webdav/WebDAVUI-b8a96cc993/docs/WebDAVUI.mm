    <p>
      <span style="font-weight: bold;">WevDavUI</span>
    </p>
    <p>
      
    </p>
    <p>
      A simple WebDAV 'explorer': lets you browse folders ('collections') and view files.
    </p>
    <p>
      Note: this is a simple project - it only shows folders and files, no properties, no locks , doesn't support PUT etc.
    </p>
    <p>
      <br/>
      In fact: the only thing we do is to issue a PROPFIND and process the resultant XML to show a file/folder layout.
    </p>
    <p>
      
    </p>
    <p>
      The UI is written in XForms - using XSLTForms implementation.
    </p>
  </body>
