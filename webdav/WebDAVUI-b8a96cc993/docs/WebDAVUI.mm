  <body>
    <p>
      Unfortunately we can't use XProc to generate our HTML in this instance.
    </p>
    <p>
      - The xsltforms.xsl is version 1.0 - and XMLCalabash doesn't support this.
    </p>
    <p>
      - We can modify the version attribute to present as 2.0 : but unfortunately this only works for some files.
    </p>
    <p>
      &#xa0;&#xa0;- In particular it doesn't work for the WebDAV namespace (which isn't a URL, but just short URN).
    </p>
    <p>
      
    </p>
    <p>
      However: it is more than capable of running through the xincludes, and copying assets such as CSS and JS files.
    </p>
    <p>
      So - probably we could do most of the tasks in our 'build.xpl' - and just do the final step (conversion to HTML5) and maybe the (optional) tidy-up-namespaces step separately.
    </p>
    <p>
      
    </p>
